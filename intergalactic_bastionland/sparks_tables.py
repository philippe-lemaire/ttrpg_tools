def gen_spark_table(data):
    name = data[0]
    table_1_name = data[1]
    table_2_name = data[2]
    table_1_values = data[3::2]
    table_2_values = data[4::2]
    return Spark_Table(
        name=name,
        table_1_name=table_1_name,
        table_1_values=table_1_values,
        table_2_name=table_2_name,
        table_2_values=table_2_values,
    )


SPARK_TABLES = {
    "people": [gen_spark_table(data) for data in people_sparks_datasets],
    "ship": [gen_spark_table(data) for data in ship_sparks_datasets],
}
